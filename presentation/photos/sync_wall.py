"""Keep photos/wall in step with photos/fotos-japan.

The presentation's photo wall can only show what is listed in photos/wall/manifest.js
(a browser cannot list a folder or open HEIC files). This script makes that list match
the folder: every photo in fotos-japan gets a light JPEG copy in wall/, copies of photos
that were removed are deleted, and manifest.js is rewritten. Only new or changed photos
are converted, so running it again is fast.

Run it with "Abrir presentacion.bat" (one folder up) or:  py -3 photos/sync_wall.py
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'fotos-japan')
OUT = os.path.join(HERE, 'wall')
INDEX = os.path.join(OUT, 'index.json')
MANIFEST = os.path.join(OUT, 'manifest.js')
EXTS = ('.jpg', '.jpeg', '.png', '.webp', '.heic', '.heif')
MAX_SIDE, QUALITY = 1000, 80


def load_imaging():
    """Import Pillow (+ HEIC support), installing them the first time if they are missing."""
    try:
        from PIL import Image, ImageOps
        import pillow_heif
    except ImportError:
        print('Instalando lo necesario para leer las fotos (Pillow, pillow-heif); solo ocurre la primera vez...')
        subprocess.check_call([sys.executable, '-m', 'pip', 'install', '--quiet', '--disable-pip-version-check', 'pillow', 'pillow-heif'])
        from PIL import Image, ImageOps
        import pillow_heif
    pillow_heif.register_heif_opener()
    return Image, ImageOps


def main():
    if not os.path.isdir(SRC):
        print('No existe la carpeta', SRC)
        return 1
    os.makedirs(OUT, exist_ok=True)
    try:
        index = json.load(open(INDEX, encoding='utf-8'))
    except (OSError, ValueError):
        index = {}
    if not index:  # no record of what is what: start clean
        for f in os.listdir(OUT):
            if f.lower().endswith('.jpg'):
                os.remove(os.path.join(OUT, f))

    sources = sorted(f for f in os.listdir(SRC) if f.lower().endswith(EXTS))
    removed = [name for name in index if name not in sources]
    for name in removed:
        path = os.path.join(OUT, index.pop(name)['out'])
        if os.path.exists(path):
            os.remove(path)

    def signature(name):
        st = os.stat(os.path.join(SRC, name))
        return '%d-%d' % (st.st_size, st.st_mtime_ns)

    todo = [n for n in sources if n not in index or index[n]['sig'] != signature(n)
            or not os.path.exists(os.path.join(OUT, index[n]['out']))]
    added, failed = 0, []
    if todo:
        Image, ImageOps = load_imaging()
        used = {int(v['out'][:-4]) for v in index.values()}
        counter = max(used, default=0)
        for i, name in enumerate(todo, 1):
            try:
                im = Image.open(os.path.join(SRC, name))
                if im.format == 'JPEG':
                    im.draft('RGB', (MAX_SIDE * 2, MAX_SIDE * 2))  # decode big camera files at reduced size: much faster
                im = ImageOps.exif_transpose(im).convert('RGB')
                im.thumbnail((MAX_SIDE, MAX_SIDE), Image.LANCZOS)
                if name in index:
                    out = index[name]['out']
                else:
                    counter += 1
                    out = '%03d.jpg' % counter
                im.save(os.path.join(OUT, out), 'JPEG', quality=QUALITY, optimize=True, progressive=True)
                index[name] = {'out': out, 'sig': signature(name)}
                added += 1
            except Exception as exc:  # one unreadable file must not stop the rest
                failed.append((name, str(exc)[:90]))
            if i % 20 == 0 or i == len(todo):
                print('  %d / %d' % (i, len(todo)))

    photos = [index[n]['out'] for n in sources if n in index]
    json.dump(index, open(INDEX, 'w', encoding='utf-8'), ensure_ascii=False, indent=0)
    with open(MANIFEST, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('// generated by photos/sync_wall.py from photos/fotos-japan (do not edit by hand)\n')
        fh.write('window.WALL_PHOTOS = ' + json.dumps(photos) + ';\n')

    print('Muro de fotos: %d en total (%d nuevas o cambiadas, %d quitadas).' % (len(photos), added, len(removed)))
    for name, why in failed:
        print('  No se pudo leer:', name.encode('ascii', 'replace').decode(), '-', why)
    return 0


if __name__ == '__main__':
    sys.exit(main())
